APPROACH = (
    "Меняться медленно, по одной привычке. Наблюдать с любопытством, а не контролировать. "
    "Не получилось — не повод бросать: принципы можно иногда нарушать и не расстраиваться."
)


def as_text() -> str:
    lines = [f"{i}. {title}. {text}" for i, (title, text) in enumerate(CODEX, 1)]
    return "\n".join(lines) + f"\nПодход ко всему: {APPROACH}"


def title(index: int) -> str:
    return CODEX[index % len(CODEX)][0]
